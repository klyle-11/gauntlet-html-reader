// Halftone ramps for the "dots" skin, generated as CSS background layers so they
// work without JavaScript, in print, and in exported pages.

/** Fraction of a square cell covered by its centred dot, radius in cell widths. */
function coverage(r: number): number {
  if (r <= 0.5) return Math.PI * r * r;
  if (r >= Math.SQRT1_2) return 1;
  // Nothing outside the cell is nearer its own dot, so this is the dot's share alone.
  return Math.PI * r * r - 4 * (r * r * Math.acos(0.5 / r) - 0.5 * Math.sqrt(r * r - 0.25));
}

/** Radius, in cell widths, whose dot covers `t` of its cell; full darkness overshoots so no gaps show. */
function radiusFor(t: number): number {
  if (t >= 0.999) return 0.74;
  let lo = 0;
  let hi = Math.SQRT1_2;
  for (let i = 0; i < 30; i++) {
    const mid = (lo + hi) / 2;
    if (coverage(mid) < t) lo = mid;
    else hi = mid;
  }
  return hi;
}

const smooth = (t: number) => t * t * (3 - 2 * t);

export interface RampOptions {
  /** Rows (or columns) of dots; each step is half the gap. */
  steps: number;
  /** Distance between dots in the same row, in px. */
  gap: number;
  /** Rows run across the page ('y') or columns run down it ('x'). */
  axis: 'x' | 'y';
  /** The edge the dots are anchored to and grow toward. */
  edge: 'top' | 'bottom' | 'right';
  /** Darkness at the anchored edge. 1 merges into a solid band. */
  darkness: number;
}

/**
 * Background layers for a staggered (45°) dot grid whose dots shrink away from
 * one edge. One layer per row, so radii can vary while staying pure CSS.
 * Dot color comes from `--ramp-dot` on the element.
 */
export function rampLayers(o: RampOptions): string {
  const s = o.gap / Math.SQRT2; // nearest-neighbour spacing, the cell the coverage maths uses
  const layers: string[] = [];
  for (let i = 0; i < o.steps; i++) {
    // Two full rows at a solid edge, so it meets the band above without slivers.
    const solid = o.darkness >= 1 ? 2 : 0;
    const t = i < solid ? 1 : o.darkness * smooth(1 - (i - solid + 0.5) / (o.steps - solid));
    const r = s * radiusFor(t);
    if (r < 0.45) continue;
    const along = ((i % 2) * o.gap) / 2;
    const from = ((i - 1) * o.gap) / 2; // tile offset so the dot's centre sits i half-gaps from the edge
    const dot = `radial-gradient(circle, var(--ramp-dot) ${r.toFixed(2)}px, transparent ${(r + 0.6).toFixed(2)}px)`;
    const size = `${o.gap}px ${o.gap}px`;
    const pos =
      o.axis === 'x'
        ? `right ${from}px top ${along}px / ${size} repeat-y`
        : `left ${along}px ${o.edge} ${from}px / ${size} repeat-x`;
    layers.push(`${dot} ${pos}`);
  }
  return layers.join(',\n    ');
}

const height = (o: RampOptions) => (o.steps * o.gap) / 2;

/** The generated half of the dots skin: page-band ramps and the module cover's dotted edge. */
export function dotsRampCss(): string {
  const band: RampOptions = { steps: 15, gap: 18, axis: 'y', edge: 'top', darkness: 1 };
  const coverX: RampOptions = { steps: 16, gap: 20, axis: 'x', edge: 'right', darkness: 0.82 };
  const coverY: RampOptions = { steps: 10, gap: 18, axis: 'y', edge: 'bottom', darkness: 0.82 };
  return `
/* Generated by src/render/dots.ts: halftone ramps, one background layer per row of dots. */
:root[data-skin="dots"] .ramp {
  display: block;
  height: ${height(band)}px;
  --ramp-dot: var(--ink);
  background:
    ${rampLayers(band)},
    var(--paper);
}
:root[data-skin="dots"] .mod-head {
  --ramp-dot: var(--paper);
  padding-right: ${height(coverX) + 24}px;
  background:
    ${rampLayers(coverX)},
    var(--ink);
}
@media (max-width: 640px) {
  :root[data-skin="dots"] .mod-head {
    padding-right: 1.25rem;
    padding-bottom: ${height(coverY) + 12}px;
    background:
      ${rampLayers(coverY)},
      var(--ink);
  }
}
`;
}
